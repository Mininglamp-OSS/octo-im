// Package sendresult carries the persistence outcome of an API send from the
// channel slot leader back to the node that accepted the HTTP request.
//
// An API send is a system-device channel event. It has no connection, so the
// regular SENDACK path never reports its outcome. The accepting node registers
// a waiter keyed by the message id it generated for one submission attempt and
// stamps its own node id into Event.SourceNodeId. The leader reports the result
// of that attempt once persist() has finished. A missing report is never read
// as success: the waiter times out as outcome unknown.
package sendresult

import (
	"errors"
	"sync"

	wkproto "github.com/WuKongIM/WuKongIMGoProto"
)

// CapabilityPath is served by nodes that report API send outcomes. A remote
// leader that does not serve it would never report, so the caller must not
// submit an acknowledged send through it.
const CapabilityPath = "/wk/channel/sendresult/capability/v1"

type Outcome uint8

const (
	// OutcomePersisted: committed and applied; MessageId/MessageSeq are canonical.
	OutcomePersisted Outcome = 1
	// OutcomeRejected: definitely not persisted and replaying will not help.
	OutcomeRejected Outcome = 2
	// OutcomeUnavailable: definitely not persisted; a replay is safe.
	OutcomeUnavailable Outcome = 3
	// OutcomeUnknown: the attempt may have committed or may commit later.
	OutcomeUnknown Outcome = 4
)

func (o Outcome) String() string {
	switch o {
	case OutcomePersisted:
		return "persisted"
	case OutcomeRejected:
		return "rejected"
	case OutcomeUnavailable:
		return "unavailable"
	case OutcomeUnknown:
		return "unknown"
	}
	return "invalid"
}

func (o Outcome) valid() bool { return o >= OutcomePersisted && o <= OutcomeUnknown }

// Result is the outcome of one submission attempt.
type Result struct {
	Key        int64 // message id generated by the accepting node for the attempt
	Outcome    Outcome
	MessageId  int64 // canonical message id, set when persisted
	MessageSeq uint64
	Reason     wkproto.ReasonCode
}

var ErrClosed = errors.New("send result registry closed")

// Registry routes results to in-flight waiters. Results without a waiter are
// dropped: the request already returned and reported its own outcome.
type Registry struct {
	mu      sync.Mutex
	waiters map[int64]chan<- Result
	closed  bool
	done    chan struct{}
}

func NewRegistry() *Registry {
	return &Registry{waiters: make(map[int64]chan<- Result), done: make(chan struct{})}
}

// Default is shared by the API server and the channel handler of one process.
var Default = NewRegistry()

// Register binds key to ch. ch must have room for every result that can be
// routed to it; Complete never blocks.
func (r *Registry) Register(key int64, ch chan<- Result) error {
	r.mu.Lock()
	defer r.mu.Unlock()
	if r.closed {
		return ErrClosed
	}
	if _, ok := r.waiters[key]; ok {
		return errors.New("duplicate send result key")
	}
	r.waiters[key] = ch
	return nil
}

func (r *Registry) Unregister(key int64) {
	r.mu.Lock()
	delete(r.waiters, key)
	r.mu.Unlock()
}

// Complete delivers a result to its waiter and reports whether one existed.
// The waiter is removed so a key is completed at most once.
func (r *Registry) Complete(res Result) bool {
	r.mu.Lock()
	ch, ok := r.waiters[res.Key]
	if ok {
		delete(r.waiters, res.Key)
	}
	r.mu.Unlock()
	if !ok {
		return false
	}
	select {
	case ch <- res:
		return true
	default:
		return false
	}
}

// Close rejects new waiters and wakes current ones through Done.
func (r *Registry) Close() {
	r.mu.Lock()
	defer r.mu.Unlock()
	if r.closed {
		return
	}
	r.closed = true
	close(r.done)
}

// Open accepts waiters again after Close, for a server started again in the
// same process. Waiters released by Close have already returned.
func (r *Registry) Open() {
	r.mu.Lock()
	defer r.mu.Unlock()
	if r.closed {
		r.closed = false
		r.done = make(chan struct{})
	}
}

func (r *Registry) Done() <-chan struct{} {
	r.mu.Lock()
	defer r.mu.Unlock()
	return r.done
}

// Pending returns the number of registered waiters.
func (r *Registry) Pending() int {
	r.mu.Lock()
	defer r.mu.Unlock()
	return len(r.waiters)
}

func Encode(results []Result) []byte {
	enc := wkproto.NewEncoder()
	enc.WriteUint32(uint32(len(results)))
	for _, res := range results {
		enc.WriteInt64(res.Key)
		enc.WriteUint8(uint8(res.Outcome))
		enc.WriteInt64(res.MessageId)
		enc.WriteUint64(res.MessageSeq)
		enc.WriteUint8(res.Reason.Byte())
	}
	return enc.Bytes()
}

func Decode(data []byte) ([]Result, error) {
	dec := wkproto.NewDecoder(data)
	count, err := dec.Uint32()
	if err != nil {
		return nil, err
	}
	// Each result occupies 26 bytes; reject counts the payload cannot hold.
	if uint64(count)*26 > uint64(len(data)) {
		return nil, errors.New("invalid send result count")
	}
	results := make([]Result, 0, count)
	for i := uint32(0); i < count; i++ {
		var res Result
		var outcome, reason uint8
		if res.Key, err = dec.Int64(); err != nil {
			return nil, err
		}
		if outcome, err = dec.Uint8(); err != nil {
			return nil, err
		}
		if res.MessageId, err = dec.Int64(); err != nil {
			return nil, err
		}
		if res.MessageSeq, err = dec.Uint64(); err != nil {
			return nil, err
		}
		if reason, err = dec.Uint8(); err != nil {
			return nil, err
		}
		res.Outcome, res.Reason = Outcome(outcome), wkproto.ReasonCode(reason)
		if !res.Outcome.valid() {
			return nil, errors.New("invalid send result outcome")
		}
		results = append(results, res)
	}
	return results, nil
}
